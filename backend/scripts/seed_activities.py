def main() -> None:
    db = get_db()
    ensure_demo_user()
    count = 0
    for act in ACTIVITIES:
        act["created_at"] = datetime.now(timezone.utc)
        db.activities.update_one(
            {"activity_id": act["activity_id"]},
            {"$set": act},
            upsert=True,
        )
        count += 1
    total = db.activities.count_documents({})
    cats = {}
    for c in db.activities.distinct("category"):
        cats[c] = db.activities.count_documents({"category": c})
    print(f"Seeded {count} activities ({total} total in collection).")
    for c, n in sorted(cats.items()):
        print(f"  {c}: {n}")
    print(f"Demo user ensured: {config.DEMO_USER_ID}")


if __name__ == "__main__":
    main()
